// JoinFragment is what `site add` hands every EXISTING post: the new post's
// [[peers]] block (with the one key it carries) and, per existing post, the
// [[destinations]] it gains. `peer apply` merges it into one post's file.
type JoinFragment struct {
	Kind           string      `toml:"kind"` // "join"
	SiteID         string      `toml:"site_id"`
	KeyFingerprint string      `toml:"key_fingerprint"`
	Peer           config.Peer `toml:"peer"`
	Destinations   []JoinDest  `toml:"destination"`
}

// JoinDest is one destination an existing post (At) gains.
type JoinDest struct {
	At            string `toml:"at"`
	ID            string `toml:"id"`
	DisplayName   string `toml:"display_name"`
	Controlled    bool   `toml:"controlled"`
	TravelMinutes int64  `toml:"travel_minutes"`
}

// LeaveFragment is what `site retire` (run at the retiring post) hands
// every remaining post. It carries no secret.
type LeaveFragment struct {
	Kind        string      `toml:"kind"` // "leave"
	SiteID      string      `toml:"site_id"`
	DisplayName string      `toml:"display_name"`
	LongName    string      `toml:"long_name"`
	FinalHeads  []FinalHead `toml:"final_head"`
}

// FinalHead is the retiring post's last sequence number in one epoch.
type FinalHead struct {
	Epoch int64 `toml:"epoch"`
	Head  int64 `toml:"head"`
}

func renderJoin(f JoinFragment) string {
	var b strings.Builder
	b.WriteString("# SiteControl JOIN fragment — generated by `sitectl admin site add` (FIX16 H).\n")
	b.WriteString("# ⚠ Carries ONE secret: the new post's peer key. Copy it like a site.toml — never email it.\n")
	b.WriteString("# At EVERY existing post:  sitectl admin peer apply -config site.toml " + "join-" + f.SiteID + ".toml\n")
	fmt.Fprintf(&b, "kind = \"join\"\nsite_id = %s\nkey_fingerprint = %s\n\n", tomlStr(f.SiteID), tomlStr(f.KeyFingerprint))
	blk := RenderPeerBlock(f.Peer)
	b.WriteString(strings.Replace(blk, "[[peers]]", "[peer]", 1))
	for _, d := range f.Destinations {
		fmt.Fprintf(&b, "\n[[destination]]\nat = %s\nid = %s\ndisplay_name = %s\ncontrolled = %t\n", tomlStr(d.At), tomlStr(d.ID), tomlStr(d.DisplayName), d.Controlled)
		if d.TravelMinutes > 0 {
			fmt.Fprintf(&b, "travel_minutes = %d\n", d.TravelMinutes)
		}
	}
	return b.String()
}

func renderLeave(f LeaveFragment) string {
	var b strings.Builder
	b.WriteString("# SiteControl LEAVE fragment — generated by `sitectl admin site retire` (FIX16 H). No secrets.\n")
	b.WriteString("# At EVERY remaining post:  sitectl admin peer remove -config site.toml leave-" + f.SiteID + ".toml\n")
	fmt.Fprintf(&b, "kind = \"leave\"\nsite_id = %s\ndisplay_name = %s\n", tomlStr(f.SiteID), tomlStr(f.DisplayName))
	if f.LongName != "" {
		fmt.Fprintf(&b, "long_name = %s\n", tomlStr(f.LongName))
	}
	for _, h := range f.FinalHeads {
		fmt.Fprintf(&b, "\n[[final_head]]\nepoch = %d\nhead = %d\n", h.Epoch, h.Head)
	}
	return b.String()
}

// LoadJoin / LoadLeave read a fragment and refuse the other kind.
func LoadJoin(path string) (*JoinFragment, error) {
	var f JoinFragment
	if err := decodeStrict(path, &f); err != nil {
		return nil, err
	}
	if f.Kind != "join" {
		return nil, fmt.Errorf("%s is not a join fragment (kind %q)", path, f.Kind)
	}
	if f.SiteID == "" || f.Peer.SiteID != f.SiteID || f.Peer.Key == "" || f.Peer.BaseURL == "" {
		return nil, fmt.Errorf("%s: incomplete join fragment", path)
	}
	if Fingerprint(f.Peer.Key) != f.KeyFingerprint {
		return nil, fmt.Errorf("%s: the key does not match its stated fingerprint %s — the file was altered or damaged in transit; get a fresh copy", path, f.KeyFingerprint)
	}
	return &f, nil
}

func LoadLeave(path string) (*LeaveFragment, error) {
	var f LeaveFragment
	if err := decodeStrict(path, &f); err != nil {
		return nil, err
	}
	if f.Kind != "leave" || f.SiteID == "" {
		return nil, fmt.Errorf("%s is not a leave fragment", path)
	}
	return &f, nil
}

func decodeStrict(path string, v any) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	meta, err := toml.Decode(string(raw), v)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if u := meta.Undecoded(); len(u) > 0 {
		return fmt.Errorf("%s: unknown key %q", path, u[0].String())
	}
	return nil
}

// ApplyJoin merges a join fragment into one post's config text. It returns
// the new text and what changed, or a refusal. The result has passed
// config.Parse; the caller writes it.
func ApplyJoin(text string, f *JoinFragment) (string, []string, error) {
	cfg, err := config.Parse([]byte(text), "site.toml")
	if err != nil {
		return "", nil, fmt.Errorf("the current file does not load: %w", err)
	}
	switch {
	case f.SiteID == cfg.SiteID:
		return "", nil, fmt.Errorf("REFUSED: this fragment adds %s, which is THIS post — apply it at the other posts", f.SiteID)
	case hasPeer(cfg, f.SiteID):
		return "", nil, fmt.Errorf("REFUSED: %s is already a peer here — nothing to do (if its key changed, that is a rekey, not a join)", f.SiteID)
	case hasFormer(cfg, f.SiteID):
		return "", nil, fmt.Errorf("REFUSED: %s was retired here ([[former_peers]]); a returning post must come back under a NEW site_id so its old and new records never mix", f.SiteID)
	}
	var mine []config.Destination
	for _, d := range f.Destinations {
		if d.At == cfg.SiteID {
			mine = append(mine, config.Destination{ID: d.ID, DisplayName: d.DisplayName, Controlled: d.Controlled, TravelMinutes: d.TravelMinutes})
		}
	}
	var notes []string
	out := text
	// Destinations must stay EXPLICIT across a join: a file with one peer
	// and no destinations key derives one controlled destination per peer
	// (config.DestinationList), and adding a peer would silently arm a
	// deadline toward the newcomer (D-77). So the old derived list is
	// written out, and a post that ends with none says so.
	explicitBefore := len(cfg.Destinations) > 0
	if !explicitBefore {
		derived := cfg.DestinationList()
		var blocks []string
		for _, d := range derived {
			blocks = append(blocks, RenderDestinationBlock(d))
			notes = append(notes, fmt.Sprintf("wrote the destination to %s explicitly (it was derived from the single peer, which stops being true now)", d.ID))
		}
		if len(derived)+len(mine) > 0 {
			out, _ = dropEmptyDestinations(out)
			out = appendBlocks(out, blocks...)
		} else if !emptyDestsLine(out) {
			out = addTopLevelLine(out, "destinations = []   # this post dispatches nowhere")
			notes = append(notes, "wrote `destinations = []` (with two or more peers the list must be explicit)")
		}
	} else if len(mine) > 0 {
		out, _ = dropEmptyDestinations(out)
	}
	out = appendBlocks(out, RenderPeerBlock(f.Peer))
	notes = append(notes, fmt.Sprintf("added peer %s (%s) at %s, key %s", f.SiteID, f.Peer.DisplayName, f.Peer.BaseURL, f.KeyFingerprint))
	for _, d := range mine {
		out = appendBlocks(out, RenderDestinationBlock(d))
		kind := "gated"
		if !d.Controlled {
			kind = "ungated"
		}
		notes = append(notes, fmt.Sprintf("added destination %s (%s, %d min)", d.ID, kind, d.TravelMinutes))
	}
	nc, err := config.Parse([]byte(out), "site.toml (edited)")
	if err != nil {
		return "", nil, fmt.Errorf("REFUSED: the edited file would not start: %w", err)
	}
	if !hasPeer(nc, f.SiteID) {
		return "", nil, fmt.Errorf("REFUSED: internal: the edited file does not list %s", f.SiteID)
	}
	return out, notes, nil
}

func countArray(text, name string) int {
	n := 0
	for _, sec := range splitSections(text) {
		if sec.array && sec.name == name {
			n++
		}
	}
	return n
}

func emptyDestsLine(text string) bool {
	_, found := dropEmptyDestinations(text)
	return found
}

// ApplyLeave removes a retired post from one post's config text: its
// [[peers]] and [[destinations]] blocks go, a [[former_peers]] entry keeps
// its name. Refuses if this post names it as the entrance.
func ApplyLeave(text string, f *LeaveFragment) (string, []string, error) {
	cfg, err := config.Parse([]byte(text), "site.toml")
	if err != nil {
		return "", nil, fmt.Errorf("the current file does not load: %w", err)
	}
	switch {
	case f.SiteID == cfg.SiteID:
		return "", nil, fmt.Errorf("REFUSED: %s is THIS post; a retired post's own file is not edited — the laptop is backed up and wiped", f.SiteID)
	case hasFormer(cfg, f.SiteID) && !hasPeer(cfg, f.SiteID):
		return "", nil, fmt.Errorf("REFUSED: %s is already retired here — nothing to do", f.SiteID)
	case !hasPeer(cfg, f.SiteID):
		return "", nil, fmt.Errorf("REFUSED: %s is not a peer here", f.SiteID)
	case cfg.EntranceSiteID == f.SiteID:
		return "", nil, fmt.Errorf("REFUSED: this post names %s as the site entrance (entrance_site_id) — change or remove that line first", f.SiteID)
	}
	name, long := f.DisplayName, f.LongName
	for _, p := range cfg.Peers {
		if p.SiteID == f.SiteID {
			if name == "" {
				name = p.DisplayName
			}
			if long == "" {
				long = p.LongName
			}
		}
	}
	out, np := removeArrayEntries(text, "peers", "site_id", f.SiteID)
	out, nd := removeArrayEntries(out, "destinations", "id", f.SiteID)
	notes := []string{fmt.Sprintf("removed peer %s", f.SiteID)}
	if np != 1 {
		return "", nil, fmt.Errorf("REFUSED: expected one [[peers]] block for %s, found %d", f.SiteID, np)
	}
	if nd > 0 {
		notes = append(notes, fmt.Sprintf("removed %d destination(s) to %s", nd, f.SiteID))
	}
	if countArray(out, "destinations") == 0 && !emptyDestsLine(out) {
		out = addTopLevelLine(out, "destinations = []   # this post dispatches nowhere")
		notes = append(notes, "wrote `destinations = []` (no destination left; never derived from peers)")
	}
	out = appendBlocks(out, RenderFormerPeerBlock(config.FormerPeer{SiteID: f.SiteID, DisplayName: name, LongName: long}))
	notes = append(notes, fmt.Sprintf("kept its name: [[former_peers]] %s = %q", f.SiteID, name))
	nc, err := config.Parse([]byte(out), "site.toml (edited)")
	if err != nil {
		return "", nil, fmt.Errorf("REFUSED: the edited file would not start: %w", err)
	}
	if hasPeer(nc, f.SiteID) {
		return "", nil, fmt.Errorf("REFUSED: internal: %s is still a peer after the edit", f.SiteID)
	}
	return out, notes, nil
}

func hasPeer(c *config.Config, id string) bool {
	for _, p := range c.Peers {
		if p.SiteID == id {
			return true
		}
	}
	return false
}

func hasFormer(c *config.Config, id string) bool {
	for _, p := range c.FormerPeers {
		if p.SiteID == id {
			return true
		}
	}
	return false
}

// AddResult is `site add`'s output summary: no secrets.
type AddResult struct{ Lines []string }

// AddSite adds one post to a running mesh. live is any live post's config
// (its file holds every key in the mesh, §1 of the design); selfURL is that
// post's own base_url (its own file cannot say it); add is a plan holding
// exactly ONE [[post]] — the newcomer — plus its [[route]]s to existing
// posts and its [[ungated]] pads. Writes outDir/<new>/site.toml,
// outDir/join-<new>.toml and outDir/passwords-<new>.txt. Refuses, writing
// nothing, on any problem.
func AddSite(liveText []byte, selfURL string, add *Plan, outDir string) (*AddResult, error) {
	live, err := config.Parse(liveText, "the live post's site.toml")
	if err != nil {
		return nil, err
	}
	var probs []string
	pf := func(f string, a ...any) { probs = append(probs, fmt.Sprintf(f, a...)) }
	if len(add.Posts) != 1 {
		return nil, refusal([]string{fmt.Sprintf("the new-post file must hold exactly one [[post]] (the newcomer); it holds %d", len(add.Posts))})
	}
	np := add.Posts[0]
	// The newcomer alone, through the season rules.
	solo := &Plan{Posts: []PlanPost{np}, SyncIntervalSeconds: add.SyncIntervalSeconds, MusterMinGroupSize: add.MusterMinGroupSize, ThemeCookieDomain: add.ThemeCookieDomain}
	probs = append(probs, solo.Validate()...)
	// The existing mesh, as the live file sees it.
	existing := []PlanPost{{SiteID: live.SiteID, DisplayName: live.PostName(), LongName: live.LongName, BaseURL: strings.TrimSuffix(selfURL, "/")}}
	if live.RoadWorkEnabled() {
		existing[0].RoadWork = &config.RoadWork{DisplayName: live.RoadWork.DisplayName}
	}
	secrets := map[string]Secrets{live.SiteID: {PeerKey: live.PeerKey}}
	for _, p := range live.Peers {
		pp := PlanPost{SiteID: p.SiteID, DisplayName: p.DisplayName, LongName: p.LongName, BaseURL: p.BaseURL}
		if p.RoadWorkLabel != "" {
			pp.RoadWork = &config.RoadWork{DisplayName: p.RoadWorkLabel}
		}
		existing = append(existing, pp)
		secrets[p.SiteID] = Secrets{PeerKey: p.Key}
	}
	if u := strings.TrimSuffix(selfURL, "/"); u == "" {
		pf("-self-url is required: the base_url the other posts use for %s (its own file cannot say it)", live.SiteID)
	} else {
		for _, p := range live.Peers {
			if strings.TrimSuffix(p.BaseURL, "/") == u {
				pf("-self-url %s is %s's address, not %s's", u, p.SiteID, live.SiteID)
			}
		}
	}
	for _, e := range existing {
		switch {
		case e.SiteID == np.SiteID:
			pf("%s is already a post in this mesh — to replace its laptop use `sitectl admin swap`", np.SiteID)
		case strings.EqualFold(strings.TrimSpace(e.DisplayName), strings.TrimSpace(np.DisplayName)):
			pf("display_name %q is already %s's", np.DisplayName, e.SiteID)
		case strings.TrimSuffix(e.BaseURL, "/") == strings.TrimSuffix(np.BaseURL, "/"):
			pf("base_url %s is already %s's", np.BaseURL, e.SiteID)
		}
	}
	if hasFormer(live, np.SiteID) {
		pf("%s is a RETIRED post's id; a new post needs a new site_id so its records never mix with the old ones", np.SiteID)
	}
	isExisting := map[string]bool{}
	for _, e := range existing {
		isExisting[e.SiteID] = true
	}
	for i, r := range add.Routes {
		other := ""
		switch {
		case r.A == np.SiteID:
			other = r.B
		case r.B == np.SiteID:
			other = r.A
		default:
			pf("route[%d] (%s-%s): every road in an add file must have the new post at one end", i, r.A, r.B)
			continue
		}
		if !isExisting[other] {
			pf("route[%d]: %s is not a post in this mesh", i, other)
		}
		if r.TravelMinutes < 0 {
			pf("route[%d]: travel_minutes must be positive", i)
		}
	}
	for i, u := range add.Ungated {
		if u.At != np.SiteID {
			pf("ungated[%d]: an add file may only give the NEW post ungated pads (edit an existing post's own file for its pads)", i)
		}
	}
	if add.Entrance != "" {
		pf("entrance cannot be set by an add file (it is in every post's file)")
	}
	if len(probs) > 0 {
		return nil, refusal(probs)
	}
	if ok, err := dirEmptyOrAbsent(outDir); err != nil {
		return nil, err
	} else if !ok {
		return nil, fmt.Errorf("REFUSED: %s is not empty — use a new, empty folder", outDir)
	}
	whole := &Plan{SyncIntervalSeconds: add.SyncIntervalSeconds, MusterMinGroupSize: add.MusterMinGroupSize, ThemeCookieDomain: add.ThemeCookieDomain, Entrance: live.EntranceSiteID,
		Posts: append(existing, np), Routes: add.Routes, Ungated: add.Ungated, FormerPeers: live.FormerPeers}
	if whole.SyncIntervalSeconds == 0 {
		whole.SyncIntervalSeconds = live.SyncIntervalSeconds
	}
	if whole.MusterMinGroupSize == nil {
		m := live.MusterMinGroupSize
		whole.MusterMinGroupSize = &m
	}
	if whole.ThemeCookieDomain == "" {
		whole.ThemeCookieDomain = live.ThemeCookieDomain
	}
	secrets[np.SiteID] = Secrets{PeerKey: NewKey(), LoginPassword: NewPassword()}
	text := whole.RenderPost(np, secrets)
	var nc *config.Config
	nc, err = config.Parse([]byte(text), np.SiteID+"/site.toml")
	if err != nil {
		return nil, refusal([]string{"the generated file would not start: " + err.Error()})
	}
	frag := JoinFragment{Kind: "join", SiteID: np.SiteID, KeyFingerprint: Fingerprint(secrets[np.SiteID].PeerKey), Peer: PeerEntry(np, secrets[np.SiteID].PeerKey)}
	for _, e := range existing {
		for _, d := range whole.destinationsFor(e.SiteID) {
			frag.Destinations = append(frag.Destinations, JoinDest{At: e.SiteID, ID: d.ID, DisplayName: d.DisplayName, Controlled: d.Controlled, TravelMinutes: d.TravelMinutes})
		}
	}
	// Prove the fragment merges into the live file and the merged mesh
	// matches up, before anything is written.
	fragText := renderJoin(frag)
	var reloaded JoinFragment
	if _, err := toml.Decode(fragText, &reloaded); err != nil {
		return nil, fmt.Errorf("internal: join fragment does not decode: %w", err)
	}
	merged, _, err := ApplyJoin(string(liveText), &reloaded)
	if err != nil {
		return nil, refusal([]string{"the join fragment would not apply to " + live.SiteID + ": " + err.Error()})
	}
	mc, err := config.Parse([]byte(merged), "merged")
	if err != nil {
		return nil, refusal([]string{err.Error()})
	}
	if pr := pairCheck(mc, nc); len(pr) > 0 {
		return nil, refusal(pr)
	}
	if err := os.MkdirAll(filepath.Join(outDir, np.SiteID), 0o700); err != nil {
		return nil, err
	}
	if err := WriteSecretFile(filepath.Join(outDir, np.SiteID, "site.toml"), []byte(text)); err != nil {
		return nil, err
	}
	if err := WriteSecretFile(filepath.Join(outDir, "join-"+np.SiteID+".toml"), []byte(fragText)); err != nil {
		return nil, err
	}
	if err := WriteSecretFile(filepath.Join(outDir, "passwords-"+np.SiteID+".txt"), []byte(fmt.Sprintf("%s (%s) login password: %s\nFor the officer handover sheet; then delete this file.\n", np.DisplayName, np.SiteID, secrets[np.SiteID].LoginPassword))); err != nil {
		return nil, err
	}
	res := &AddResult{Lines: []string{
		fmt.Sprintf("  %s/site.toml: new post %s accepts %s, %d peer(s), %d destination(s)", np.SiteID, np.SiteID, frag.KeyFingerprint, len(nc.Peers), len(nc.DestinationList())),
		fmt.Sprintf("  join-%s.toml: apply at each of the %d existing post(s) with `sitectl admin peer apply`, then restart each", np.SiteID, len(existing)),
		fmt.Sprintf("  passwords-%s.txt: the new post's login password (0600)", np.SiteID),
	}}
	for _, d := range frag.Destinations {
		res.Lines = append(res.Lines, fmt.Sprintf("  %s gains destination %s (%d min)", d.At, d.ID, d.TravelMinutes))
	}
	return res, nil
}

// pairCheck is CrossCheck restricted to two posts: each holds the other's
// accepted key and lists the other.
func pairCheck(a, b *config.Config) []string {
	var probs []string
	find := func(c *config.Config, id string) *config.Peer {
		for i := range c.Peers {
			if c.Peers[i].SiteID == id {
				return &c.Peers[i]
			}
		}
		return nil
	}
	if p := find(a, b.SiteID); p == nil || p.Key != b.PeerKey {
		probs = append(probs, fmt.Sprintf("%s would not hold the key %s accepts", a.SiteID, b.SiteID))
	}
	if p := find(b, a.SiteID); p == nil || p.Key != a.PeerKey {
		probs = append(probs, fmt.Sprintf("%s would not hold the key %s accepts", b.SiteID, a.SiteID))
	}
	return probs
}
