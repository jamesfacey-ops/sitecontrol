// w5eRefusalArm describes one error-returning return statement.
type w5eRefusalArm struct {
	Line int
	Text string
	// ⟦LOCK — §72, 2026-09-03⟧ plainWrap: this arm wraps an `err` received from
	// a call rather than constructing its error here. One half of the
	// propagation test; see w5eCensusRefusals.
	plainWrap bool
}

// w5eCensusRefusals is THE detector: every `return <T>, <non-nil>` in the
// named function, described by its fmt.Errorf format literal where it has
// one and by the printed error expression otherwise. Covering the
// non-fmt.Errorf case matters — a length cap written as
// `return Trip{}, errCargoTooLong` is still a new refusal.
func w5eCensusRefusals(t *testing.T, path string, src []byte, fnName string) ([]w5eRefusalArm, bool) {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, 0)
	if err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	var arms []w5eRefusalArm
	found := false
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Name.Name != fnName || fn.Body == nil {
			continue
		}
		found = true
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			ret, ok := n.(*ast.ReturnStmt)
			if !ok || len(ret.Results) != 2 {
				return true
			}
			last := ret.Results[1]
			if id, ok := last.(*ast.Ident); ok && id.Name == "nil" {
				return true
			}
			// ⟦LOCK — §72, 2026-09-03⟧ ⟦was: "\t\t\tarms = append(arms, w5eRefusalArm{Line: fset.Position(ret.Pos()).Line, Text: w5eDescribeError(last)})"⟧
			arms = append(arms, w5eRefusalArm{
				Line: fset.Position(ret.Pos()).Line, Text: w5eDescribeError(last),
				plainWrap: w5eIsPlainErrWrap(last),
			})
			return true
		})
	}
	// ⟦LOCK — §72, 2026-09-03⟧ ⭐ PROPAGATIONS ARE DROPPED HERE, MECHANICALLY.
	//
	// ⚠ THE SUBJECT IS THE REFUSAL SET; THE FILTER WAS COUNTING EVERY ERROR
	// RETURN. Third filter-wider-than-its-subject in a census today, after
	// §63's RefAlias scan and the seeded-vs-folded check.
	//
	// THE PROPERTY, stated so the code sorts the arms and no human classifies
	// them one at a time ⟦§72(3)⟧ — an arm is a PROPAGATION when BOTH hold:
	//
	//	(a) its format string contributes NO TEXT OF ITS OWN — it is exactly the
	//	    prefix every arm in this function already shares, plus `%w`; and
	//	(b) its `%w` argument is a PLAIN IDENTIFIER — an `err` received from a
	//	    call — rather than an error CONSTRUCTED at the return site.
	//
	// ⚠ THE SHARED PREFIX IS DERIVED FROM THE ARMS THEMSELVES, never written
	// down: hard-coding "domain: dispatch: " would be the hand-kept list again,
	// one level down, and would silently stop working the day the function is
	// renamed.
	//
	// ⚠ BOTH CONDITIONS ARE REQUIRED, and each earns its place:
	//
	//	· (a) alone would drop `"…: driver: %w"` and `"…: occupant: %w"`, which
	//	  wrap `requireRosterPerson` — F11's dangling-reference REFUSAL. §72's
	//	  suggested "wraps an err ⇒ propagation" rule would have silenced both,
	//	  the exact loss its own stop-condition guards against.
	//	· (b) alone would drop the placeholder refusal that stood at position 2
	//	  until W7-25(e) relocated it: its format WAS the bare prefix + `%w`, but
	//	  it wrapped `vehicleIDRefusal(...)` — an error CONSTRUCTED there. A rule
	//	  that mis-classifies a known historical refusal is not a rule.
	//
	// ⭐ The bias is deliberate and is §72's own: "I would rather pin four
	// propagations forever than lose the ability to see a refusal appear."
	// ⟦was: "So `"…: phase gate: %w"` STAYS PINNED …" — that arm was deleted
	// with weather phases, James 2026-10-04⟧
	prefix := w5eSharedPrefix(arms)
	kept := arms[:0:0]
	for _, a := range arms {
		if a.plainWrap && a.Text == prefix+"%w" {
			continue
		}
		kept = append(kept, a)
	}
	return kept, found
}

// w5eIsPlainErrWrap reports whether e is `fmt.Errorf(<literal>, <ident>)` — a
// wrap of an error RECEIVED from a call, as opposed to one constructed at the
// return site. ⟦LOCK — §72, 2026-09-03⟧
func w5eIsPlainErrWrap(e ast.Expr) bool {
	call, ok := e.(*ast.CallExpr)
	if !ok || len(call.Args) != 2 {
		return false
	}
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Errorf" {
		return false
	}
	if pkg, ok := sel.X.(*ast.Ident); !ok || pkg.Name != "fmt" {
		return false
	}
	_, isIdent := call.Args[1].(*ast.Ident)
	return isIdent
}

// w5eSharedPrefix is the longest prefix common to every arm's description —
// the text this function contributes to all of its errors alike, and therefore
// the text that distinguishes none of them. ⟦LOCK — §72, 2026-09-03⟧
func w5eSharedPrefix(arms []w5eRefusalArm) string {
	if len(arms) == 0 {
		return ""
	}
	prefix := arms[0].Text
	for _, a := range arms[1:] {
		for !strings.HasPrefix(a.Text, prefix) {
			prefix = prefix[:len(prefix)-1]
			if prefix == "" {
				return ""
			}
		}
	}
	return prefix
}

// w5eDescribeError prints one refusal's identity: its fmt.Errorf format
// literal, or the source text of whatever else is returned.
func w5eDescribeError(e ast.Expr) string {
	if call, ok := e.(*ast.CallExpr); ok {
		if sel, ok := call.Fun.(*ast.SelectorExpr); ok {
			if pkg, ok := sel.X.(*ast.Ident); ok && pkg.Name == "fmt" && sel.Sel.Name == "Errorf" && len(call.Args) > 0 {
				if l, ok := call.Args[0].(*ast.BasicLit); ok && l.Kind == token.STRING {
					if s, err := strconv.Unquote(l.Value); err == nil {
						return s
					}
				}
			}
		}
	}
	return "NON-FORMAT REFUSAL: " + types.ExprString(e)
}

